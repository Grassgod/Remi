function exemptRoute(route: string): CliManifestRoute | null {
  const path = route.slice(route.indexOf(" ") + 1);
  const exempt = (category: CliExemptCategory, reason: string): CliManifestRoute => ({
    cli_exempt: true,
    category,
    reason,
  });
  if (path === "/ws" || path === "/api/daemon/ws" || path === "/api/realtime/ws") {
    return exempt("websocket_transport", "Long-lived WebSocket transport is outside the CLI command surface.");
  }
  if (path.startsWith("/api/daemon/") || /\/runtimes\/[^/]+\/heartbeat$/.test(path) || path === "/api/multiremi/scheduler/tick") {
    return exempt("daemon_internal_protocol", "Daemon heartbeat, claim, report, and execution protocol is machine-to-server traffic.");
  }
  if (path === "/api/multiremi/autopilots/:id/run-scheduled") {
    return exempt("daemon_internal_protocol", "Scheduler execution is machine-to-server traffic; users trigger an autopilot with remi autopilot run.");
  }
  if (path === "/api/multiremi/autopilots/:id/webhook") {
    return exempt("oauth_or_webhook_callback", "Autopilot webhook reception is invoked by an external system, not a user command.");
  }
  if (path === "/api/knowledge/events/repository-merged") {
    return exempt("daemon_internal_protocol", "SCM merge event ingestion is machine-to-server automation traffic; it is not a user command.");
  }
  if (path.startsWith("/api/webhooks/") || /\/(oauth|google|lark)\/callback$/.test(path)) {
    return exempt("oauth_or_webhook_callback", "External provider callback is authenticated and invoked by the provider, not a user command.");
  }
  if (path.startsWith("/api/platform-updater/")) {
    return exempt("platform_updater_internal", "Platform updater callback is an internal deployment control-plane protocol.");
  }
  if (path === "/api/cli/latest-version") {
    return exempt("platform_updater_internal", "Dashboard-only release discovery gates the CLI update control; CLI update workflows use runtime release commands.");
  }
  if (path === "/api/config" || path === "/api/contact-sales") {
    return exempt("pure_ui", "Browser bootstrap or presentation-only action has no meaningful CLI workflow.");
  }
  if (path === "/" || path === "/favicon.ico") {
    return exempt("public_bootstrap_asset", "Public service bootstrap asset has no user-side CLI operation.");
  }
  return null;
}

function plannedCommand(route: string): { domain: string; command: string } {
  const separator = route.indexOf(" ");
  const method = route.slice(0, separator);
  const path = route.slice(separator + 1);
  const segments = path.split("/").filter(Boolean);
  if (segments[0] === "api") segments.shift();
  if (segments[0] === "multiremi") segments.shift();
  let rawDomain = segments[0] ?? "platform";
  if (rawDomain === "workspaces" && segments.includes("scm")) rawDomain = "scm";
  else if (rawDomain === "workspaces" && segments.includes("feishu")) rawDomain = "feishu";
  else if (rawDomain === "issues" && segments.includes("change-requests")) rawDomain = "scm";
  else if (rawDomain === "workspaces" && segments.includes("lark")) rawDomain = "lark";
  else if (rawDomain === "workspaces" && segments.includes("session-archive")) rawDomain = "session";
  if (rawDomain === "auth") rawDomain = "context";
  if (rawDomain === "me") rawDomain = "member";
  if (rawDomain === "remi" || rawDomain === "install.sh") rawDomain = "platform";
  if (rawDomain === "cli-token") rawDomain = "token";
  if (rawDomain === "upload-file") rawDomain = "attachment";
  if (rawDomain === "lark") rawDomain = "lark";
  const domain = DOMAIN_ALIASES[rawDomain] ?? rawDomain;
  const staticTail = [...segments].reverse().find((segment) => !segment.startsWith(":")) ?? rawDomain;
  const collection = segments.length <= 1 || (segments.length === 2 && segments[1] === "search");
  let action = method === "GET" ? (collection ? "list" : "get")
    : method === "DELETE" ? "delete"
      : method === "PATCH" || method === "PUT" ? "update"
        : collection ? "create" : normalizeAction(staticTail);
  if (staticTail === "search") action = "search";
  if (path === "/health" || path === "/healthz" || path === "/readyz"
    || path === "/health/realtime" || path === "/api/multiremi/health") action = "status";
  if (staticTail === "archive" || staticTail === "restore" || staticTail === "verify" || staticTail === "retry"
    || staticTail === "cancel" || staticTail === "respond" || staticTail === "checkout" || staticTail === "trigger") {
    action = staticTail;
  }
  return { domain, command: `${domain}.${action}` };
}

function normalizeAction(value: string): string {
  return value.replace(/[^a-zA-Z0-9]+/g, "_").replace(/^_+|_+$/g, "") || "update";
}

